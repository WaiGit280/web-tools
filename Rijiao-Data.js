function rijiaoLeapMonth(y) {
  if (y < 1900 || y > 2100) return 0;
  return RIJIAO_LUNAR_INFO[y - 1900] & 0xf;
}

function rijiaoLeapDays(y) {
  return rijiaoLeapMonth(y) ? ((RIJIAO_LUNAR_INFO[y - 1900] & 0x10000) ? 30 : 29) : 0;
}

function rijiaoMonthDays(y, m) {
  if (y < 1900 || y > 2100) return 29;
  return (RIJIAO_LUNAR_INFO[y - 1900] & (0x10000 >> m)) ? 30 : 29;
}

function rijiaoYearDays(y) {
  let s = 348;
  for (let i = 0x8000; i > 0x8; i >>= 1) {
    s += (RIJIAO_LUNAR_INFO[y - 1900] & i) ? 1 : 0;
  }
  return s + rijiaoLeapDays(y);
}

function rijiaoBuildMonthList(y) {
  const months = [];
  const leap = rijiaoLeapMonth(y);
  for (let m = 1; m <= 12; m++) {
    months.push({ m, d: rijiaoMonthDays(y, m), leap: false });
    if (m === leap) {
      months.push({ m, d: rijiaoLeapDays(y), leap: true });
    }
  }
  return months;
}

function gregorianToLunar(gy, gm, gd) {
  const baseUtc = Date.UTC(1900, 0, 31);
  const targetUtc = Date.UTC(gy, gm - 1, gd);
  let off = Math.round((targetUtc - baseUtc) / 86400000);
  if (off < 0) return null;
  let ly;
  for (ly = 1900; ly <= 2100; ly++) {
    const yd = rijiaoYearDays(ly);
    if (off < yd) break;
    off -= yd;
  }
  if (ly > 2100) return null;
  const months = rijiaoBuildMonthList(ly);
  let lm = 1;
  let isLeap = false;
  for (let i = 0; i < months.length; i++) {
    if (off < months[i].d) {
      lm = months[i].m;
      isLeap = months[i].leap;
      break;
    }
    off -= months[i].d;
  }
  return { y: ly, m: lm, d: off + 1, leap: isLeap };
}

function lunarToGregorian(ly, lm, ld, isLeap) {
  if (ly < 1900 || ly > 2100) return null;
  let off = 0;
  for (let y = 1900; y < ly; y++) off += rijiaoYearDays(y);
  const months = rijiaoBuildMonthList(ly);
  let found = false;
  for (let i = 0; i < months.length; i++) {
    if (months[i].m === lm && months[i].leap === !!isLeap) {
      if (ld < 1 || ld > months[i].d) return null;
      found = true;
      break;
    }
    off += months[i].d;
  }
  if (!found) return null;
  off += ld - 1;
  const utc = Date.UTC(1900, 0, 31) + off * 86400000;
  const dt = new Date(utc);
  return { y: dt.getUTCFullYear(), m: dt.getUTCMonth() + 1, d: dt.getUTCDate() };
}

function shiftGregorianDate(gy, gm, gd, deltaDays) {
  const utc = Date.UTC(gy, gm - 1, gd) + deltaDays * 86400000;
  const dt = new Date(utc);
  return { y: dt.getUTCFullYear(), m: dt.getUTCMonth() + 1, d: dt.getUTCDate() };
}

